'use strict';

/**
 * Refresh docs/metrics.md from the run logs. Nothing here is estimated: a
 * number that cannot be computed from a log is printed as a dash.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..');
const RUNS = path.join(ROOT, 'runs');

function readJsonl(dir) {
  if (!fs.existsSync(dir)) return [];
  const out = [];
  for (const name of fs.readdirSync(dir)) {
    if (!name.endsWith('.jsonl')) continue;
    for (const line of fs.readFileSync(path.join(dir, name), 'utf8').split('\n')) {
      if (!line.trim()) continue;
      try { out.push(JSON.parse(line)); } catch { /* skip a torn line */ }
    }
  }
  return out;
}

const mean = (xs) => (xs.length ? Math.round(xs.reduce((a, b) => a + b, 0) / xs.length) : null);
const pct = (a, b) => (b ? `${Math.round((a / b) * 1000) / 10}%` : '—');

function phase2() {
  const recs = fs.existsSync(RUNS)
    ? fs.readdirSync(RUNS).filter((f) => f.endsWith('.jsonl')).flatMap((f) =>
        fs.readFileSync(path.join(RUNS, f), 'utf8').split('\n').filter(Boolean).map((l) => {
          try { return JSON.parse(l); } catch { return null; }
        }).filter(Boolean))
    : [];
  if (!recs.length) return null;
  return {
    runs: recs.length,
    correct: recs.filter((r) => r.correct).length,
    tokens: recs.reduce((n, r) => n + (r.tokens || 0), 0),
    meanLatencyS: mean(recs.map((r) => r.latencyMs || 0)) / 1000,
    meanBrowserS: mean(recs.filter((r) => r.durationMs).map((r) => r.durationMs)) / 1000,
  };
}

function phase3() {
  // Only records that reached execution count; earlier lines are harness
  // iterations where the planner or generator itself failed.
  const all = readJsonl(path.join(RUNS, 'phase3')).filter((r) => r.stages && r.stages.executor);
  // One record per case: keep the last attempt, so a retried case is not counted twice.
  const byCase = new Map();
  for (const r of all) byCase.set(r.case, r);
  const recs = [...byCase.values()];
  if (!recs.length) return null;
  return {
    cases: recs.length,
    detected: recs.filter((r) => r.detected).length,
    missed: recs.filter((r) => r.missed).length,
    misclassified: recs.filter((r) => r.misclassified).length,
  };
}

function phase4() {
  const file = path.join(RUNS, 'phase4', 'report.json');
  if (!fs.existsSync(file)) return null;
  return JSON.parse(fs.readFileSync(file, 'utf8')).summary;
}

function phase5() {
  const full30 = path.join(RUNS, 'phase5', 'executed-30.json');
  const file = fs.existsSync(full30) ? full30 : path.join(RUNS, 'phase5', 'executed.json');
  if (!fs.existsSync(file)) return null;
  const data = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (data.summary) {
    return {
      executed: data.summary.executed,
      caught: data.summary.executed - data.summary.missedDefects,
      fullS: null,
      shardWallS: null,
      wallS: Math.round(data.summary.wallSeconds),
    };
  }
  return {
    executed: (data.executed || []).length,
    caught: (data.executed || []).filter((e) => e.caught).length,
    fullS: data.timing ? data.timing.fullSeconds : null,
    shardWallS: data.timing ? data.timing.shardedWallSeconds : null,
  };
}

function build() {
  const p2 = phase2();
  const p3 = phase3();
  const p4 = phase4();
  const p5 = phase5();
  const lines = [];
  lines.push('# Metrics');
  lines.push('');
  lines.push('Generated by `node agents/metrics/summarise.js` from `runs/`. A dash means the number could not be computed from a log; nothing here is estimated.');
  lines.push('');
  lines.push('| Phase | Runs | Success | Tokens | Latency | Note |');
  lines.push('|---|---|---|---|---|---|');
  lines.push(
    `| 2 - Single agent | ${p2 ? p2.runs : '—'} | ${p2 ? pct(p2.correct, p2.runs) : '—'} | ${p2 ? p2.tokens.toLocaleString() : '—'} | ${p2 ? `${p2.meanLatencyS}s model / ${p2.meanBrowserS}s browser` : '—'} | all runs, all iterations |`,
  );
  lines.push(
    `| 3 - Agent team | ${p3 ? p3.cases : '—'} | ${p3 ? pct(p3.detected, p3.cases) : '—'} | — | — | ${p3 ? `${p3.missed} missed, ${p3.misclassified} misclassified` : '—'} |`,
  );
  lines.push(
    `| 4 - Reviewer | ${p4 ? p4.cases : '—'} | ${p4 ? pct(p4.agrees, p4.cases) : '—'} | — | — | ${p4 ? `${p4.escalated} escalated` : '—'} |`,
  );
  lines.push(
    `| 5 - Release | ${p5 ? p5.executed : '—'} | ${p5 ? pct(p5.caught, p5.executed) : '—'} | — | ${p5 ? (p5.fullS !== null && p5.fullS !== undefined ? `${p5.fullS}s full / ${p5.shardWallS}s sharded` : `${p5.wallS}s for ${p5.executed} sets`) : '—'} | executed change sets |`,
  );
  lines.push('');
  lines.push('## What these numbers do not say');
  lines.push('');
  lines.push('- Token counts are not money: the provider publishes no per-token price.');
  lines.push('- Phase 4 success is agreement with labels written by the project itself, not an independent human.');
  lines.push('- Phase 5 counts only the change sets actually executed.');
  lines.push('');
  return lines.join('\n');
}

const out = build();
fs.writeFileSync(path.join(ROOT, 'docs', 'metrics.md'), out);
console.log(out);
